export interface ThreatFilters {
  threatModel?: number | string
  blueprint?: number
  component?: number
  flow?: number
  zone?: number
  boundary?: number
  threatLibrary?: number
  status?: ThreatStatusValue
  triageStatus?: TriageStatus
  level?: RatingLevel
  number?: number
  wholeSystem?: boolean
  /** Matches the name, and `T7` or `7` the number. */
  search?: string
  ordering?: string
}

function threatQueryString(filters: ThreatFilters): string {
  const params = new URLSearchParams()
  if (filters.threatModel !== undefined) params.set('threat_model', String(filters.threatModel))
  if (filters.blueprint !== undefined) params.set('blueprint', String(filters.blueprint))
  if (filters.component !== undefined) params.set('component', String(filters.component))
  if (filters.flow !== undefined) params.set('flow', String(filters.flow))
  if (filters.zone !== undefined) params.set('zone', String(filters.zone))
  if (filters.boundary !== undefined) params.set('boundary', String(filters.boundary))
  if (filters.threatLibrary !== undefined) params.set('threat_library', String(filters.threatLibrary))
  if (filters.status) params.set('status', filters.status)
  if (filters.triageStatus) params.set('triage_status', filters.triageStatus)
  if (filters.level) params.set('rating__level', filters.level)
  if (filters.number !== undefined) params.set('number', String(filters.number))
  if (filters.wholeSystem !== undefined) params.set('whole_system', filters.wholeSystem ? 'true' : 'false')
  if (filters.search) params.set('search', filters.search)
  if (filters.ordering) params.set('ordering', filters.ordering)
  return params.toString()
}


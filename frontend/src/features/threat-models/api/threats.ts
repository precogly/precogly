/**
 * Threats matching the filters, from `/threats/`. Pass `enabled: false`
 * through `options` when the filter is not ready.
 */
export function useThreats(filters: ThreatFilters, options: { enabled?: boolean } = {}) {
  return useQuery({
    queryKey: threatKeys.list(filters),
    queryFn: async () => {
      const query = threatQueryString(filters)
      const response = await api.get<{ results: InstanceThreat[] } | InstanceThreat[]>(
        query ? `/threats/?${query}` : '/threats/'
      )
      return Array.isArray(response) ? response : response.results
    },
    enabled: options.enabled ?? true,
  })
}

export function useThreat(threatId: number | null) {
  return useQuery({
    queryKey: threatKeys.detail(threatId ?? -1),
    queryFn: threatId !== null ? () => api.get<InstanceThreat>(`/threats/${threatId}/`) : skipToken,
  })
}


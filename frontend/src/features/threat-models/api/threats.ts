function countermeasureQueryString(filters: CountermeasureFilters): string {
  const params = new URLSearchParams()
  if (filters.threatModel !== undefined) params.set('threat_model', String(filters.threatModel))
  if (filters.countermeasureLibrary !== undefined) {
    params.set('countermeasure_library', String(filters.countermeasureLibrary))
  }
  if (filters.status) params.set('status', filters.status)
  if (filters.requiredForRelease !== undefined) {
    params.set('required_for_release', filters.requiredForRelease ? 'true' : 'false')
  }
  if (filters.number !== undefined) params.set('number', String(filters.number))
  if (filters.overdue) params.set('overdue', 'true')
  return params.toString()
}


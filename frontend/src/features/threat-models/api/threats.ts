/**
 * Transform the analysis payload into the screen's `AnalysisThreat` shape.
 */
export function transformAnalysisThreats(payloadThreats: AnalysisPayloadThreat[]): AnalysisThreat[] {
  const now = new Date().toISOString()

  return payloadThreats.map((payloadThreat) => {
    const uiThreatId = threatUiId(payloadThreat.id)
    const firstTarget = payloadThreat.targets[0]

    const countermeasures: AnalysisCountermeasure[] = payloadThreat.countermeasures.map((cm) => ({
      id: countermeasureUiId(cm.id),
      countermeasureId: cm.countermeasureLibraryId ? `lib-${cm.countermeasureLibraryId}` : 'custom',
      componentThreatId: uiThreatId,
      status: cm.status as CountermeasureStatus,
      priority: (cm.priority || 'none') as AnalysisCountermeasure['priority'],
      dueDate: cm.dueDate ?? null,
      externalTicketUrl: cm.externalTicketUrl || undefined,
      owner: cm.assignedOwnerEmail || undefined,
      notes: cm.evidenceUrl || undefined,
      createdAt: now,
      updatedAt: now,
      backendCountermeasureId: cm.id,
      number: cm.number,
      displayNumber: cm.displayNumber,
      autoGenerated: cm.autoGenerated,
      targets: cm.targets ?? [],
      implementedBy: cm.implementedBy ?? [],
      implementedByParty: cm.implementedByParty || undefined,
      source: cm.source || undefined,
      countermeasureName: cm.countermeasureName || undefined,
      countermeasureDescription: cm.countermeasureDescription || undefined,
      controlFunctions: cm.controlFunctions || [],
      controlNature: cm.controlNature || '',
      standardMappings: cm.standardMappings || [],
      displayOrder: cm.displayOrder ?? 0,
      alsoMitigates: cm.alsoMitigates || [],
      isShared: (cm.alsoMitigates && cm.alsoMitigates.length > 0) || false,
    }))

    return {
      id: uiThreatId,
      diagramId: firstTarget?.dfdId || '',
      sourceDiagramId: firstTarget?.dfdId || undefined,
      sourceDiagramTitle: firstTarget?.dfdName || undefined,
      threatId: payloadThreat.threatLibraryId ? `lib-${payloadThreat.threatLibraryId}` : 'custom',
      triageStatus: payloadThreat.triageStatus || 'open',
      decisionRationale: payloadThreat.decisionRationale || '',
      countermeasures,
      createdAt: now,
      updatedAt: now,
      backendThreatId: payloadThreat.id,
      number: payloadThreat.number,
      displayNumber: payloadThreat.displayNumber,
      wholeSystem: payloadThreat.wholeSystem,
      targets: payloadThreat.targets ?? [],
      autoGenerated: payloadThreat.autoGenerated,
      libraryMismatch: payloadThreat.libraryMismatch,
      threatName: payloadThreat.threatName || undefined,
      threatDescription: payloadThreat.threatDescription || undefined,
      taxonomyEntries: payloadThreat.taxonomyEntries,
      rating: payloadThreat.rating,
      displayOrder: payloadThreat.displayOrder ?? 0,
      componentName: firstTarget?.name || undefined,
      impactDescription: payloadThreat.impactDescription || undefined,
      threatActorText: payloadThreat.threatActorText || undefined,
      actorPersonaId: payloadThreat.actorPersonaId,
      actorPersonaName: payloadThreat.actorPersonaName,
      intent: payloadThreat.intent || undefined,
      accessLevel: payloadThreat.accessLevel || undefined,
    }
  })
}

export interface ThreatAnalysisData extends ThreatAnalysisResponse {
  /** The payload's threats in the screen's shape. */
  analysisThreats: AnalysisThreat[]
}

/**
 * Fetch every scenario of a threat model with its countermeasures and canvas
 * placement (one payload builder, F29).
 */
export function useThreatModelThreats(threatModelId: string | null | undefined) {
  return useQuery({
    queryKey: analysisKeys.model(threatModelId ?? ''),
    queryFn: threatModelId
      ? async (): Promise<ThreatAnalysisData> => {
          const response = await api.get<ThreatAnalysisResponse>(`/threat-models/${threatModelId}/threats/`)
          return {
            ...response,
            analysisThreats: transformAnalysisThreats(response.threats),
          }
        }
      : skipToken,
    staleTime: 30000, // Consider fresh for 30 seconds
  })
}


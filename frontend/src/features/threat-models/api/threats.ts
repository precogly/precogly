function invalidateThreatReaders(queryClient: ReturnType<typeof useQueryClient>) {
  queryClient.invalidateQueries({ queryKey: threatKeys.all })
  queryClient.invalidateQueries({ queryKey: analysisKeys.all })
  queryClient.invalidateQueries({ queryKey: ['threat-models'] })
}

function invalidateCountermeasureReaders(queryClient: ReturnType<typeof useQueryClient>) {
  invalidateThreatReaders(queryClient)
  queryClient.invalidateQueries({ queryKey: countermeasureKeys.all })
  queryClient.invalidateQueries({ queryKey: ['countermeasures-in-use'] })
  queryClient.invalidateQueries({ queryKey: riskKeys.all })
}


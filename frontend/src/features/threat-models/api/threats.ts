/**
 * API hooks for threats, countermeasures, personas and the analysis payload.
 *
 * One threat table: `/api/threats/` serves every scenario whatever it
 * targets (plan section 4.1). A scenario has `targets[]` (component, flow,
 * zone, boundary) or is `wholeSystem`. Countermeasures live at
 * `/api/countermeasures/` with their own `targets[]` (where the control
 * applies; empty means the whole system) and `implementedBy` (the components
 * that implement it).
 *
 * Query strings stay snake_case (lib/api.ts does not rewrite them); bodies
 * and responses are camelCase.
 */

